package ai

import (
	"errors"
	"time"
)

const (
	// AILabel enforces FR-AI-06: every AI output must be labeled explicitly.
	AILabel = "Dibuat dengan bantuan AI - periksa kembali"
)

var (
	ErrAIDisabledForRT       = errors.New("fitur asisten AI dinonaktifkan untuk RT ini (FR-AI-07)")
	ErrProviderUnavailable   = errors.New("layanan asisten AI tidak tersedia (koneksi terputus atau offline)")
	ErrProviderTimeout       = errors.New("waktu tunggu permintaan ke model AI habis (timeout)")
	ErrInvalidModelResponse   = errors.New("respons dari model AI tidak valid atau tidak dapat diuraikan")
	ErrEmptyInput            = errors.New("pesan atau data input untuk asisten AI tidak boleh kosong")
	ErrUnauthorizedAISettings = errors.New("hanya pengurus RT atau admin wilayah yang memiliki hak mengubah pengaturan AI")
)

// RawMessage represents a message before entering the anonymization boundary.
type RawMessage struct {
	ID            string    `json:"id"`
	BlockID       string    `json:"block_id"`
	Text          string    `json:"text"`
	SenderName    string    `json:"sender_name,omitempty"`
	SenderPhone   string    `json:"sender_phone,omitempty"`
	SenderAddress string    `json:"sender_address,omitempty"`
	Timestamp     time.Time `json:"timestamp"`
}

// AnonMessage represents a message that has been sanitized according to FR-AI-05.
// Contains NO real names, NO phone numbers, NO street addresses, and NO personal health notes.
type AnonMessage struct {
	ID        string    `json:"id"`
	BlockID   string    `json:"block_id"`
	Text      string    `json:"text"`
	Timestamp time.Time `json:"timestamp"`
}

// Summary holds block-by-block points and an overall situational summary (FR-AI-01).
type Summary struct {
	PointsByBlock  map[string][]string `json:"points_by_block"`
	OverallSummary string              `json:"overall_summary"`
	AIAssisted     bool                `json:"ai_assisted"`
	Label          string              `json:"label"`
	GeneratedAt    time.Time           `json:"generated_at"`
}

// NeedsSuggestion provides structured need suggestions from message text (FR-AI-02).
type NeedsSuggestion struct {
	Needs         []string  `json:"needs"`
	NeedsMask     int       `json:"needs_mask"`
	Urgency       string    `json:"urgency"` // "biasa" or "kritis"
	HasVulnerable bool      `json:"has_vulnerable"`
	Confidence    float64   `json:"confidence"`
	Reasoning     string    `json:"reasoning"`
	AIAssisted    bool      `json:"ai_assisted"`
	Label         string    `json:"label"`
	GeneratedAt   time.Time `json:"generated_at"`
}

// RecapAggregate contains aggregated numbers for AI narrative drafting (FR-AI-03).
// Absolutely zero personal citizen identities or individual health records are passed.
type RecapAggregate struct {
	RTName               string  `json:"rt_name"`
	KelurahanName        string  `json:"kelurahan_name"`
	Hazard               string  `json:"hazard"`
	Duration             string  `json:"duration"`
	TotalHouseholds      int     `json:"total_households"`
	SafeHouseholds       int     `json:"safe_households"`
	ShelterHouseholds    int     `json:"shelter_households"`
	NeedHelpHouseholds   int     `json:"need_help_households"`
	VulnerableCount      int     `json:"vulnerable_count"`
	VulnerableReached    int     `json:"vulnerable_reached"`
	VulnerablePercentage float64 `json:"vulnerable_percentage"`
	NeedsEvakuasi        int     `json:"needs_evakuasi"`
	NeedsMedis           int     `json:"needs_medis"`
	NeedsMakananAir      int     `json:"needs_makanan_air"`
	NeedsHunian          int     `json:"needs_hunian"`
	NeedsLainnya         int     `json:"needs_lainnya"`
}

// DraftRecapResult represents the drafted narrative generated by the model.
type DraftRecapResult struct {
	DraftNarrative string    `json:"draft_narrative"`
	AIAssisted     bool      `json:"ai_assisted"`
	Label          string    `json:"label"`
	GeneratedAt    time.Time `json:"generated_at"`
}

// AISettings represents the toggle and status of the AI assistant for an RT (FR-AI-07).
type AISettings struct {
	RTID           string `json:"rt_id"`
	AIEnabled      bool   `json:"ai_enabled"`
	ActiveProvider string `json:"active_provider"`
	ModelName      string `json:"model_name"`
}
